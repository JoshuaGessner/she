# Every file this script can disturb, including the generated views, which
# `status.py --write` re-stamps with today's date. Restoring these verbatim is
# not optional: regenerating them instead leaves the tree dirty whenever the
# run crosses UTC midnight relative to the commit — which is precisely how CI
# caught this, since `--check` deliberately ignores the date stamp but
# `git diff` does not.
#
# `status-app.html` was missing from this list until an audit found it: it is
# regenerated by `--write` exactly like the other two and was added to the tool
# after this comment was written. The bug it caused is latent rather than
# visible — it only bites when a run crosses UTC midnight relative to the
# commit — which is precisely why nothing had noticed.
TOUCHED = [ROADMAP, TEC005, TEC002, QUESTIONS, WORKFLOW,
           ROOT / "docs" / "STATUS.md", ROOT / "docs" / "status.html",
           ROOT / "docs" / "status-app.html"]


class Trial(NamedTuple):
    code: str       # the Issue code --check must report
    why: str        # the decision this check enforces
    path: Path
    old: str
    new: str
    # Which checker is expected to notice. Defaults to status.py because every
    # trial did until ADR-104 added one that guards a workflow file rather than
    # a document, and a trial pointed at the wrong tool passes by being silent
    # — the exact failure this whole script exists to catch.
    tool: str = "status.py"
    # What the report line must name besides the code: the planted file, unless
    # the checker reports the fault where it lands (an orphaned doc, not the
    # roadmap that orphaned it). A code alone is not enough — B199 found a code
    # that every clean run already prints, so its trial could not fail.
    names: str = ""

    @property
    def expected(self) -> str:
        return self.names or self.path.name

    def reported(self, output: str) -> bool:
        return any(self.code in line and self.expected in line for line in output.splitlines())


